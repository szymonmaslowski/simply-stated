import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import type { MachineGraph } from '../types';
import { renderMermaid } from './mermaid';

const CROSS_STATE_KEY = '*';

const escapeHtml = (text: string) =>
  text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');

const readMermaidRuntime = () => {
  const resolve = createRequire(import.meta.url).resolve;
  return readFileSync(resolve('mermaid/dist/mermaid.min.js'), 'utf8').replace(
    /<\/script/gi,
    '<\\/script',
  );
};

const renderTransitionRows = (graph: MachineGraph) =>
  graph.states
    .flatMap(state =>
      state.transitions.map(transition => {
        const from =
          state.name === CROSS_STATE_KEY
            ? '<em>any state</em>'
            : escapeHtml(state.name);
        return `        <tr>
          <td>${from}</td>
          <td><code>${escapeHtml(transition.event)}</code></td>
          <td>${transition.payload === null ? '<span class="muted">—</span>' : `<code>${escapeHtml(transition.payload)}</code>`}</td>
          <td>${transition.targets.map(target => `<code>${escapeHtml(target)}</code>`).join(' | ')}</td>
        </tr>`;
      }),
    )
    .join('\n');

const renderTerminalStates = (graph: MachineGraph) => {
  const terminal = graph.states
    .filter(state => state.name !== CROSS_STATE_KEY)
    .filter(state => state.transitions.length === 0);
  if (terminal.length === 0) return '';
  return `      <p class="muted">No outgoing events: ${terminal
    .map(state => `<code>${escapeHtml(state.name)}</code>`)
    .join(', ')}</p>`;
};

const renderMachineSection = (
  graph: MachineGraph,
) => `    <section id="${escapeHtml(graph.name)}">
      <h2>${escapeHtml(graph.name)}</h2>
      <p class="muted">${escapeHtml(graph.sourceFile)}</p>
      <pre class="mermaid">${escapeHtml(renderMermaid(graph))}</pre>
${renderTerminalStates(graph)}
      <table>
        <thead>
          <tr><th>State</th><th>Event</th><th>Payload</th><th>Targets</th></tr>
        </thead>
        <tbody>
${renderTransitionRows(graph)}
        </tbody>
      </table>
    </section>`;

