export const renderHtml = (graphs: MachineGraph[]) => {
  const navigation =
    graphs.length > 1
      ? `    <nav>${graphs
          .map(
            graph =>
              `<a href="#${escapeHtml(graph.name)}">${escapeHtml(graph.name)}</a>`,
          )
          .join('')}</nav>`
      : '';

  return `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <title>simply-stated diagrams</title>
  <style>
${STYLES}
  </style>
</head>
<body>
  <main>
    <h1>State machines</h1>
    <p class="muted">${graphs.length} machine${graphs.length === 1 ? '' : 's'} · generated by simply-stated-diagram</p>
${navigation}
${graphs.map(renderMachineSection).join('\n')}
  </main>
  <script>${readMermaidRuntime()}</script>
  <script>
    mermaid.initialize({
      startOnLoad: true,
      theme: window.matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'default',
    });
  </script>
</body>
</html>
`;
};
